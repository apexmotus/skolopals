#!/usr/bin/env node
// Validates the aptitude item bank and writes db/seed/06_aptitude.sql from it.
// SPEC-2026-11-enrolment-payments-ux.md §4.3.
//
//   node db/seed/aptitude/load.mjs           regenerate the seed
//   node db/seed/aptitude/load.mjs --check   fail if the bank is invalid or the seed is stale
//
// JSON Schema (draft 2020-12, via Ajv) checks the shape. The checks it cannot
// express are done here: every answerId is one of its item's options, ids are
// unique, every passageId exists, and the blueprint can actually be served.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import Ajv2020 from "ajv/dist/2020.js";

const here = dirname(fileURLToPath(import.meta.url));
const bankPath = join(here, "aptitude_test.json");
const schemaPath = join(here, "aptitude_test.schema.json");
const seedPath = join(here, "..", "06_aptitude.sql");

const bank = JSON.parse(readFileSync(bankPath, "utf8"));
const schema = JSON.parse(readFileSync(schemaPath, "utf8"));

const problems = [];

const ajv = new Ajv2020({ allErrors: true, strict: false });
const validate = ajv.compile(schema);
if (!validate(bank)) {
  for (const e of validate.errors ?? []) problems.push(`schema: ${e.instancePath || "/"} ${e.message}`);
}

if (problems.length === 0) {
  const itemIds = new Set();
  for (const item of bank.items) {
    if (itemIds.has(item.id)) problems.push(`duplicate item id ${item.id}`);
    itemIds.add(item.id);
    const optionIds = item.options.map((o) => o.id);
    if (new Set(optionIds).size !== optionIds.length) problems.push(`${item.id}: duplicate option ids`);
    if (!optionIds.includes(item.answerId)) problems.push(`${item.id}: answerId ${item.answerId} is not an option`);
    if (item.section === "literacy" && !item.passageId) problems.push(`${item.id}: literacy item has no passageId`);
    if (item.section === "logic" && item.passageId) problems.push(`${item.id}: logic item has a passageId`);
  }

  const passageIds = new Set();
  for (const p of bank.passages) {
    if (passageIds.has(p.id)) problems.push(`duplicate passage id ${p.id}`);
    passageIds.add(p.id);
  }
  for (const item of bank.items) {
    if (item.passageId && !passageIds.has(item.passageId)) {
      problems.push(`${item.id}: passageId ${item.passageId} does not exist`);
    }
  }

  // The engine serves whole passages, so literacy items must be a sum of
  // passage sizes, and there must be enough of each section to fill the test.
  const { testLength, literacyItems, logicItems, bankSize } = bank.test.blueprint;
  const literacy = bank.items.filter((i) => i.section === "literacy");
  const logic = bank.items.filter((i) => i.section === "logic");
  if (bank.items.length !== bankSize) problems.push(`blueprint.bankSize is ${bankSize}, bank has ${bank.items.length}`);
  if (literacyItems + logicItems !== testLength) problems.push("literacyItems + logicItems must equal testLength");
  if (logic.length < logicItems) problems.push(`only ${logic.length} logic items for ${logicItems} served`);
  const passageSizes = bank.passages.map((p) => literacy.filter((i) => i.passageId === p.id).length);
  if (passageSizes.some((n) => n !== passageSizes[0])) {
    problems.push("every passage must have the same number of items");
  } else if (literacyItems % passageSizes[0] !== 0 || literacyItems / passageSizes[0] > bank.passages.length) {
    problems.push(`${literacyItems} literacy items cannot be served as whole passages of ${passageSizes[0]}`);
  }

  const { minDifficulty, maxDifficulty, startDifficulty } = bank.test.adaptive;
  if (!(minDifficulty <= startDifficulty && startDifficulty <= maxDifficulty)) {
    problems.push("adaptive.startDifficulty must sit between min and max");
  }
  const banded = bank.scoring.levels.flatMap((l) => l.bands).sort();
  if (banded.join() !== "1,2,3,4,5") problems.push("scoring.levels must cover bands 1-5 exactly once");
}

if (problems.length > 0) {
  console.error(`aptitude bank ${bank.schemaVersion ?? "?"} is invalid:`);
  for (const p of problems) console.error(`  - ${p}`);
  process.exit(1);
}

const q = (v) => (v === null || v === undefined ? "null" : `'${String(v).replaceAll("'", "''")}'`);
const j = (v) => `${q(JSON.stringify(v))}::jsonb`;
const version = bank.schemaVersion;
const t = bank.test;

const sql = `-- GENERATED by db/seed/aptitude/load.mjs from aptitude_test.json. Do not edit.
-- Regenerate with: node db/seed/aptitude/load.mjs
-- Aptitude item bank ${version}. Idempotent: re-running updates the bank in place.

insert into public.aptitude_banks
  (version, test_id, title, instructions, audience_notes, blueprint, adaptive, scoring, difficulty_bands, is_current)
values (${q(version)}, ${q(t.id)}, ${q(t.title)}, ${q(t.instructions)}, ${q(t.audience.notes ?? "")},
        ${j(t.blueprint)}, ${j(t.adaptive)}, ${j(bank.scoring)}, ${j(bank.difficultyBands)}, false)
on conflict (version) do update set
  test_id = excluded.test_id, title = excluded.title, instructions = excluded.instructions,
  audience_notes = excluded.audience_notes, blueprint = excluded.blueprint, adaptive = excluded.adaptive,
  scoring = excluded.scoring, difficulty_bands = excluded.difficulty_bands;

-- Exactly one current bank: this one.
update public.aptitude_banks set is_current = false where is_current and version <> ${q(version)};
update public.aptitude_banks set is_current = true where version = ${q(version)};

insert into public.aptitude_passages (bank_version, id, title, text) values
${bank.passages.map((p) => `  (${q(version)}, ${q(p.id)}, ${q(p.title)}, ${q(p.text)})`).join(",\n")}
on conflict (bank_version, id) do update set title = excluded.title, text = excluded.text;

insert into public.aptitude_items
  (bank_version, id, section, skill, subskill, difficulty, passage_id, stem, options, answer_id) values
${bank.items
  .map(
    (i) =>
      `  (${q(version)}, ${q(i.id)}, ${q(i.section)}, ${q(i.skill)}, ${q(i.subskill)}, ${i.difficulty}, ` +
      `${q(i.passageId)}, ${q(i.stem)}, ${j(i.options)}, ${q(i.answerId)})`,
  )
  .join(",\n")}
on conflict (bank_version, id) do update set
  section = excluded.section, skill = excluded.skill, subskill = excluded.subskill,
  difficulty = excluded.difficulty, passage_id = excluded.passage_id, stem = excluded.stem,
  options = excluded.options, answer_id = excluded.answer_id;
`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(seedPath, "utf8");
  } catch {
    // Missing counts as stale.
  }
  if (current !== sql) {
    console.error("db/seed/06_aptitude.sql is out of date. Run: node db/seed/aptitude/load.mjs");
    process.exit(1);
  }
  console.log(`aptitude bank ${version}: valid, seed up to date (${bank.items.length} items, ${bank.passages.length} passages)`);
} else {
  writeFileSync(seedPath, sql);
  console.log(`wrote ${seedPath} (${bank.items.length} items, ${bank.passages.length} passages)`);
}
